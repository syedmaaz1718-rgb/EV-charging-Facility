CREATE TABLE IF NOT EXISTS users (
  id SERIAL PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(150) NOT NULL UNIQUE,
  phone VARCHAR(20),
  password_hash VARCHAR(100) NOT NULL,
  role VARCHAR(10) NOT NULL DEFAULT 'CUSTOMER',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS vehicles (
  id SERIAL PRIMARY KEY,
  user_id INT NOT NULL,
  reg_no VARCHAR(20) NOT NULL UNIQUE,
  model VARCHAR(100),
  battery_kwh DOUBLE PRECISION,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS stations (
  id SERIAL PRIMARY KEY,
  name VARCHAR(120) NOT NULL UNIQUE,
  area VARCHAR(120),
  address VARCHAR(255),
  status VARCHAR(15) NOT NULL DEFAULT 'ONLINE',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS chargers (
  id SERIAL PRIMARY KEY,
  station_id INT NOT NULL,
  code VARCHAR(20) NOT NULL,
  type VARCHAR(10) NOT NULL,
  power_kw DOUBLE PRECISION NOT NULL,
  rate_per_kwh DOUBLE PRECISION NOT NULL,
  status VARCHAR(15) NOT NULL DEFAULT 'FREE',
  UNIQUE (station_id, code),
  FOREIGN KEY (station_id) REFERENCES stations(id)
);
CREATE TABLE IF NOT EXISTS bookings (
  id SERIAL PRIMARY KEY,
  user_id INT NOT NULL,
  vehicle_id INT NOT NULL,
  station_id INT NOT NULL,
  charger_id INT,
  charger_type VARCHAR(10) NOT NULL,
  slot_time TIMESTAMP NOT NULL,
  status VARCHAR(15) NOT NULL DEFAULT 'QUEUED',
  est_wait_min INT DEFAULT 0,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id),
  FOREIGN KEY (vehicle_id) REFERENCES vehicles(id),
  FOREIGN KEY (station_id) REFERENCES stations(id)
);
CREATE TABLE IF NOT EXISTS sessions (
  id SERIAL PRIMARY KEY,
  booking_id INT NOT NULL UNIQUE,
  charger_id INT NOT NULL,
  start_time TIMESTAMP,
  end_time TIMESTAMP,
  energy_kwh DOUBLE PRECISION DEFAULT 0,
  amount DOUBLE PRECISION DEFAULT 0,
  status VARCHAR(15) NOT NULL DEFAULT 'READY',
  FOREIGN KEY (booking_id) REFERENCES bookings(id),
  FOREIGN KEY (charger_id) REFERENCES chargers(id)
);
CREATE TABLE IF NOT EXISTS invoices (
  id SERIAL PRIMARY KEY,
  session_id INT NOT NULL UNIQUE,
  invoice_no VARCHAR(30) NOT NULL UNIQUE,
  amount DOUBLE PRECISION NOT NULL,
  status VARCHAR(10) NOT NULL DEFAULT 'UNPAID',
  issued_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (session_id) REFERENCES sessions(id)
);
CREATE TABLE IF NOT EXISTS maintenance (
  id SERIAL PRIMARY KEY,
  charger_id INT NOT NULL,
  due_date DATE NOT NULL,
  note VARCHAR(255),
  status VARCHAR(15) NOT NULL DEFAULT 'SCHEDULED',
  FOREIGN KEY (charger_id) REFERENCES chargers(id)
);
CREATE TABLE IF NOT EXISTS audit_log (
  id SERIAL PRIMARY KEY,
  actor VARCHAR(100) NOT NULL,
  action VARCHAR(255) NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
